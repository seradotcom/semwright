async fn skill_broker_call(
    client: &mut ipc::Client,
    command: &str,
    args: serde_json::Value,
) -> Result<serde_json::Value> {
    let envelope = client
        .execute(
            unique_id(),
            ExecuteRequest {
                command: command.into(),
                args,
                dry_run: false,
                backend: None,
            },
        )
        .await?;
    if let Some(error) = envelope.error {
        return Err(error);
    }
    envelope
        .data
        .ok_or_else(|| Error::new(ErrorCode::ProtocolMismatch, "Broker response has no data"))
}

async fn skill_broker_version(client: &mut ipc::Client) -> Result<String> {
    let value = skill_broker_call(client, "doctor", json!({})).await?;
    value
        .get("version")
        .and_then(serde_json::Value::as_str)
        .filter(|version| !version.is_empty() && version.len() <= 128)
        .map(ToOwned::to_owned)
        .ok_or_else(|| {
            Error::new(
                ErrorCode::ProtocolMismatch,
                "Broker doctor response has no bounded Semwright version",
            )
        })
}

fn catalog_revision(value: &serde_json::Value) -> Result<u64> {
    value
        .get("revision")
        .and_then(serde_json::Value::as_u64)
        .ok_or_else(|| {
            Error::new(
                ErrorCode::ProtocolMismatch,
                "Catalog response has no revision",
            )
        })
}

async fn skill_describe(
    client: &mut ipc::Client,
    id: &str,
    revision: &mut Option<u64>,
) -> Result<Option<skills::CatalogCapability>> {
    let value = match skill_broker_call(client, "capabilities.describe", json!({"name":id})).await {
        Ok(value) => value,
        Err(error) if error.code == ErrorCode::NotFound => return Ok(None),
        Err(error) => return Err(error),
    };
    let observed = catalog_revision(&value)?;
    if revision.is_some_and(|expected| expected != observed) {
        return Err(Error::new(
            ErrorCode::Conflict,
            "Capability catalog changed while evaluating Skill dependencies; retry",
        ));
    }
    *revision = Some(observed);
    Ok(Some(skills::catalog_capability_from_broker(&value)?))
}

async fn skill_catalog(
    client: &mut ipc::Client,
    package: &skills::SkillPackage,
) -> Result<Vec<skills::CatalogCapability>> {
    use std::collections::BTreeSet;
    let mut ids = BTreeSet::new();
    let mut revision = None;
    if let Some(requirements) = &package.requirements {
        for requirement in &requirements.semwright.capabilities {
            if let Some(id) = &requirement.id {
                ids.insert(id.clone());
            }
            let Some(query) = &requirement.query else {
                continue;
            };
            let mut offset = 0usize;
            loop {
                let source = query
                    .source
                    .map(serde_json::to_value)
                    .transpose()?
                    .unwrap_or(serde_json::Value::Null);
                let value = skill_broker_call(
                    client,
                    "capabilities.search",
                    json!({
                        "query":query.text,
                        "provider":query.provider,
                        "source":source,
                        "app":query.application,
                        "category":serde_json::Value::Null,
                        "risk":serde_json::Value::Null,
                        "available":serde_json::Value::Null,
                        "tags":query.tags,
                        "object_types":query.object_types,
                        "limit":100,
                        "offset":offset,
                        "revision":revision
                    }),
                )
                .await?;
                let observed = catalog_revision(&value)?;
                if revision.is_some_and(|expected| expected != observed) {
                    return Err(Error::new(
                        ErrorCode::Conflict,
                        "Capability catalog changed during Skill dependency search; retry",
                    ));
                }
                revision = Some(observed);
                ids.extend(skills::capability_ids_from_search(&value)?);
                match value.get("next_offset").and_then(serde_json::Value::as_u64) {
                    Some(next) => offset = next as usize,
                    None => break,
                }
            }
        }
    }
    if let Some(lock) = &package.lock {
        ids.extend(lock.entries.iter().map(|entry| entry.capability_id.clone()));
    }

    let mut catalog = Vec::new();
    for id in ids {
        if let Some(entry) = skill_describe(client, &id, &mut revision).await? {
            catalog.push(entry);
        }
    }
    Ok(catalog)
}

async fn manage_skill_remote(cli: &Cli, command: &Skill, client: &mut ipc::Client) -> Result<i32> {
    match command {
        Skill::Doctor { path } => {
            let package = skills::load(path)?;
            let broker_version = skill_broker_version(client).await?;
            let catalog = skill_catalog(client, &package).await?;
            let report = skills::doctor(&package, &catalog, &broker_version)?;
            let code = if report.semwright_compatible { 0 } else { 1 };
            print_result(&serde_json::to_value(report)?, cli.json)?;
            Ok(code)
        }
        Skill::Lock { path } => {
            let package = skills::load(path)?;
            let broker_version = skill_broker_version(client).await?;
            let catalog = skill_catalog(client, &package).await?;
            let lock = skills::lock(&package, &catalog, &broker_version)?;
            if !cli.dry_run {
                skills::write_lock(&package.root, &lock)?;
            }
            print_result(
                &json!({
                    "schema_version":1,
                    "skill":package.manifest.name,
                    "locked":!cli.dry_run,
                    "dry_run":cli.dry_run,
                    "lock":lock,
                    "authority_granted":false
                }),
                cli.json,
            )?;
            Ok(0)
        }
        Skill::Test { path } => {
            let package = skills::load(path)?;
            let broker_version = skill_broker_version(client).await?;
            let catalog = skill_catalog(client, &package).await?;
            let report = skills::conformance_test(&package, &catalog, &broker_version)?;
            let code = if report.pass { 0 } else { 1 };
            print_result(&serde_json::to_value(report)?, cli.json)?;
            Ok(code)
        }
        Skill::Export { capability, output } => {
            let mut revision = None;
            let entry = skill_describe(client, capability, &mut revision)
                .await?
                .ok_or_else(|| Error::new(ErrorCode::NotFound, "Capability was not found"))?;
            let report = skills::export_capability(&entry, output)?;
            print_result(
                &json!({
                    "schema_version":1,
                    "generated_starter":true,
                    "source_capability":capability,
                    "validation":report,
                    "authority_granted":false
                }),
                cli.json,
            )?;
            Ok(0)
        }
        Skill::Validate { .. }
        | Skill::Inspect { .. }
        | Skill::Scaffold { .. }
        | Skill::Bundle { .. } => Err(Error::new(
            ErrorCode::Internal,
            "Static Skill command reached broker-backed execution",
        )),
    }
}

async fn local(cli: &Cli) -> Result<bool> {
    match &cli.command {
        Command::Setup { config_dir } => {
            let result = setup_result(cli, config_dir.as_deref())?;
            print_setup(&result, cli.json)?;
        }
        Command::Completions { shell } => {
            clap_complete::generate(
                *shell,
                &mut Cli::command(),
                "semwright",
                &mut std::io::stdout(),
            );
        }
        Command::Man => {
            clap_mangen::Man::new(Cli::command()).render(&mut std::io::stdout())?;
        }
        Command::Mcp {
            command: Mcp::Upstream { command },
        } => {
            manage_upstream(cli, command).await?;
        }
        Command::Config { .. } => {
            let paths = semwright_platform_services::paths()?;
            let endpoint = match &cli.socket {
                Some(path) => path.clone(),
                None => ipc::default_endpoint("broker")?,
            };
            print_result(
                &json!({"runtime":paths.runtime,"socket":endpoint,"config":paths.config.join("daemon.toml"),"state":paths.state}),
                cli.json,
            )?;
        }
        Command::Skill {
            command: Skill::Validate { path },
        } => {
            let report = skills::validate(path)?;
            print_skill_validation(&report, cli.json)?;
        }
        Command::Skill {
            command: Skill::Inspect { path },
        } => {
            let package = skills::load(path)?;
            print_result(&skill_inspect_value(&package), cli.json)?;
        }
        Command::Skill {
            command: Skill::Scaffold { name, output },
        } => {
            let report = skills::scaffold(name, output)?;
            print_result(
                &json!({
                    "schema_version":1,
                    "created":output,
                    "validation":report,
                    "authority_granted":false
                }),
                cli.json,
            )?;
        }
        Command::Skill {
            command: Skill::Bundle { path, output },
        } => {
            let package = skills::load(path)?;
            if cli.dry_run {
                print_result(
                    &json!({
                        "schema_version":1,
                        "skill":package.manifest.name,
                        "output":output,
                        "created":false,
                        "dry_run":true
                    }),
                    cli.json,
                )?;
            } else {
                let report = skills::bundle(&package, output)?;
                print_result(&serde_json::to_value(report)?, cli.json)?;
            }
        }
        Command::Skill {
            command:
                Skill::Doctor { .. } | Skill::Export { .. } | Skill::Test { .. } | Skill::Lock { .. },
        } => return Ok(false),
        Command::Recipe {
            command: Recipe::Scaffold { name, output },
        } => {
            if name.is_empty()
                || name.len() > 64
                || !name
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
            {
                return Err(Error::invalid(
                    "Recipe name must be lowercase letters, digits or hyphens",
                ));
            }
            let template = include_str!("../../../recipes/fake-export.yaml").replacen(
                "name: fake-export",
                &format!("name: {name}"),
                1,
            );
            create(output, &template)?;
            print_result(&json!({"created":output,"installed":false}), cli.json)?;
        }
        Command::Driver { command } => {
            manage_driver(cli, command).await?;
        }
        Command::Plugin {
            command: Plugin::Scaffold { output, sdk_path },
        } => {
            let sdk = sdk_path.canonicalize()?;
            if !sdk.join("Cargo.toml").is_file() {
                return Err(Error::invalid(
                    "--sdk-path must be the semwright-plugin-sdk crate directory",
                ));
            }
            let parent = sdk
                .parent()
                .ok_or_else(|| Error::invalid("SDK path has no crates directory"))?;
            std::fs::create_dir(output)?;
            std::fs::create_dir(output.join("src"))?;
            // JSON strings are also valid TOML basic strings, preventing path interpolation.
            let manifest = format!(
                "[package]\nname = \"semwright-textstats-local\"\nversion = \"0.1.0\"\nedition = \"2024\"\n[dependencies]\nsemwright-plugin-sdk = {{ path = {} }}\nsemwright-types = {{ path = {} }}\nserde_json = \"1\"\ntokio = {{ version = \"1\", features = [\"macros\", \"rt\"] }}\n",
                serde_json::to_string(&sdk)?,
                serde_json::to_string(&parent.join("types"))?
            );
            create(&output.join("Cargo.toml"), &manifest)?;
            create(
                &output.join("src/main.rs"),
                include_str!("../../../adapters/example-plugin/src/main.rs"),
            )?;
            create(
                &output.join("README.md"),
                "# Local textstats plugin\n\nBuild this project, then generate a manifest with scripts/plugin-manifest.py from the Semwright repository. Review the executable digest and permissions before an operator installs it. No code is installed by scaffolding.\n",
            )?;
            print_result(
                &json!({"created":output,"installed":false,"next":"Build and generate a reviewed digest-bound manifest"}),
                cli.json,
            )?;
        }
        _ => return Ok(false),
    }
    Ok(true)
}
async fn run(cli: &Cli) -> Result<i32> {
    if local(cli).await? {
        return Ok(0);
    }
    let socket = cli
        .socket
        .clone()
        .map(Ok)
        .unwrap_or_else(ipc::default_socket)?;
    let ticket = cli
        .session_file
        .clone()
        .map(Ok)
        .unwrap_or_else(|| ipc::default_session_ticket(&socket))?;
    let mut client = ipc::connect_persistent(&socket, &ticket).await?;
    if let Command::Skill { command } = &cli.command {
        return manage_skill_remote(cli, command, &mut client).await;
    }
    if let Command::Watch { after } = &cli.command {
        ipc::write_frame(
            &mut client.stream,
            &ClientMessage::Subscribe { after: *after },
        )
        .await?;
        // Never cancel a partially consumed framed read just to send a heartbeat.
        let (mut read, mut write) = tokio::io::split(client.stream);
        let heartbeat = tokio::spawn(async move {
            let mut timer = tokio::time::interval(Duration::from_secs(30));
            loop {
                timer.tick().await;
                if ipc::write_frame(&mut write, &ClientMessage::Ping {})
                    .await
                    .is_err()
                {
                    break;
                }
            }
        });
        let result = loop {
            let message = tokio::select! {_=tokio::signal::ctrl_c()=>break Ok(0),message=ipc::read_frame::<_,ServerMessage>(&mut read)=>message};
            match message {
                Ok(ServerMessage::Event { sequence, event }) => {
                    if let Err(e) = print_result(&json!({"sequence":sequence,"event":event}), true)
                    {
                        break Err(e);
                    }
                }
                Ok(ServerMessage::Pong) => (),
                Ok(ServerMessage::Error { error }) => break Err(error),
                Ok(_) => {
                    break Err(Error::new(
                        ErrorCode::ProtocolMismatch,
                        "Unexpected event-stream frame",
                    ));
                }
                Err(e) => break Err(e),
            }
        };
        heartbeat.abort();
        return result;
    }
    if matches!(
        &cli.command,
        Command::Recipe {
            command: Recipe::Test { .. }
        }
    ) {
        let check = client
            .execute(
                unique_id(),
                ExecuteRequest {
                    command: "doctor".into(),
                    args: json!({}),
                    dry_run: false,
                    backend: None,
                },
            )
            .await?;
        if check
            .data
            .as_ref()
            .and_then(|d| d.get("fake"))
            .and_then(|v| v.as_bool())
            != Some(true)
        {
            return Err(Error::new(
                ErrorCode::PolicyDenied,
                "recipe test requires a broker started with --fake; refusing to run on a live desktop",
            ));
        }
    }
    let request = request(cli)?
        .ok_or_else(|| Error::new(ErrorCode::Internal, "Command has no request mapping"))?;
    let id = unique_id();
    let started = std::time::Instant::now();
    let result = tokio::select! {
        value=client.execute(id.clone(),request.clone())=>value,
        _=tokio::signal::ctrl_c()=>{let _=tokio::time::timeout(Duration::from_secs(1),client.cancel(id.clone())).await;Err(Error::new(ErrorCode::Cancelled,"Cancellation sent; a dispatched action may already have taken effect. Do not retry blindly.").uncertain())},
    };
    let envelope = match result {
        Ok(e) => e,
        Err(e) => Envelope::finish(
            id,
            request.command,
            "transport".into(),
            started.elapsed(),
            request.dry_run,
            Err(e.uncertain()),
        ),
    };
    let code = envelope.error.as_ref().map_or(0, Error::exit_code);
    print_result(&serde_json::to_value(envelope)?, cli.json)?;
    Ok(code)
}
#[tokio::main]
async fn main() {
    let cli = Cli::parse();
    let code = match run(&cli).await {
        Ok(code) => code,
        Err(error) => {
            if cli.json {
                let _ = print_result(&json!({"ok":false,"error":error}), true);
            } else {
                eprintln!("{}", escape_terminal_text(&error.to_string()));
            }
            error.exit_code()
        }
    };
    std::process::exit(code);
}

#[cfg(test)]
mod setup_tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn setup_file_is_non_overwriting_and_idempotent() {
        let temp = tempdir().unwrap();
        let path = temp.path().join("daemon.toml");
        assert_eq!(setup_file(&path, OBSERVE_CONFIG, false).unwrap(), "created");
        assert_eq!(
            setup_file(&path, "different", false).unwrap(),
            "kept-existing"
        );
        assert_eq!(std::fs::read_to_string(path).unwrap(), OBSERVE_CONFIG);
    }

    #[test]
    fn setup_dry_run_does_not_create_files() {
        let temp = tempdir().unwrap();
        let path = temp.path().join("daemon.toml");
        assert_eq!(
            setup_file(&path, OBSERVE_CONFIG, true).unwrap(),
            "would-create"
        );
        assert!(!path.exists());
    }

    #[test]
    fn setup_mcp_document_uses_exact_sibling_binary() {
        let doc = setup_mcp_document(
            Path::new("/opt/semwright/bin/semwright-mcp"),
            &[],
            &json!({}),
        )
        .unwrap();
        let value: Value = serde_json::from_str(&doc).unwrap();
        assert_eq!(
            value["mcpServers"]["semwright"]["command"],
            "/opt/semwright/bin/semwright-mcp"
        );
    }

    #[test]
    fn setup_explicit_directory_is_dry_run_safe_and_non_overwriting() {
        let parent = tempdir().unwrap();
        let directory = parent.path().join("owner-config");
        let mut cli = Cli::try_parse_from(["semwright", "--json", "--dry-run", "setup"]).unwrap();
        let dry = setup_result(&cli, Some(&directory)).unwrap();
        assert_eq!(dry["config"]["status"], "would-create");
        assert!(!directory.exists());

        cli.dry_run = false;
        let created = setup_result(&cli, Some(&directory)).unwrap();
        assert_eq!(created["config"]["status"], "created");
        assert_eq!(created["permissions_granted"], false);
        let config = directory.join("daemon.toml");
        let snippet = directory.join("mcp-client.json");
        let existing = std::fs::read(&snippet).unwrap();
        std::fs::write(&config, "[policy]\nprofile = \"workspace\"\n").unwrap();

        cli.socket = Some(parent.path().join("different-endpoint"));
        let repeated = setup_result(&cli, Some(&directory)).unwrap();
        assert_eq!(repeated["config"]["status"], "kept-existing");
        assert!(repeated["config"]["profile"].is_null());
        assert_eq!(repeated["mcp_client_snippet"]["status"], "kept-existing");
        assert_eq!(
            repeated["mcp_client_snippet"]["matches_requested_configuration"],
            false
        );
        assert_eq!(std::fs::read(snippet).unwrap(), existing);
        assert_eq!(
            std::fs::read_to_string(config).unwrap(),
            "[policy]\nprofile = \"workspace\"\n"
        );
    }

    #[test]
    fn setup_rejects_relative_configuration_directory() {
        let cli = Cli::try_parse_from(["semwright", "--dry-run", "setup"]).unwrap();
        assert_eq!(
            setup_result(&cli, Some(Path::new("relative-config")))
                .unwrap_err()
                .code,
            ErrorCode::InvalidArgument
        );
    }

    #[test]
    fn setup_snippet_binds_endpoint_ticket_and_private_data_environment() {
        let arguments = setup_client_args(
            Some(Path::new("endpoint with spaces")),
            Some(Path::new("ticket with spaces")),
        );
        let environment = json!({"SEMWRIGHT_DATA_DIR": "data with spaces"});
        let document =
            setup_mcp_document(Path::new("binary with spaces"), &arguments, &environment).unwrap();
        let document: Value = serde_json::from_str(&document).unwrap();
        let entry = &document["mcpServers"]["semwright"];
        assert_eq!(entry["command"], "binary with spaces");
        assert_eq!(
            entry["args"],
            json!([
                "--socket",
                "endpoint with spaces",
                "--session-file",
                "ticket with spaces"
            ])
        );
        assert_eq!(entry["env"], environment);
    }

    #[cfg(target_os = "windows")]
    #[test]
    fn setup_rejects_configuration_below_a_junction_without_writing() {
        let parent = tempdir().unwrap();
        let outside = parent.path().join("outside");
        std::fs::create_dir(&outside).unwrap();
        let link = parent.path().join("link");
        let status = std::process::Command::new("cmd")
            .args(["/C", "mklink", "/J"])
            .arg(&link)
            .arg(&outside)
            .status()
            .unwrap();
        assert!(status.success());
        let cli = Cli::try_parse_from(["semwright", "setup"]).unwrap();
        assert!(setup_result(&cli, Some(&link.join("config"))).is_err());
        assert!(!outside.join("config").exists());
        std::fs::remove_dir(link).unwrap();
    }
}
